function p(text, {tag='keep', bold=false, size=22, spacing=120, indent=0}={}) {
  const o = {
    children:[new TextRun({text, bold, size, font:'Times New Roman'})],
    spacing:{after:spacing, line:300},
  };
  if (C[tag]) o.shading = {type:ShadingType.CLEAR, fill:C[tag], color:'auto'};
  if (indent) o.indent = {left:indent};
  return new Paragraph(o);
}
function label(tag) {
  return new Paragraph({
    children:[new TextRun({text:'▌'+LBL[tag], bold:true, size:16, font:'Arial', color:'444444'})],
    spacing:{before:160, after:40},
    shading:{type:ShadingType.CLEAR, fill:C[tag], color:'auto'},
  });
}
function src(text) {
  return new Paragraph({
    children:[new TextRun({text:'Источник: '+text, italics:true, size:18, font:'Arial', color:'666666'})],
    spacing:{after:160},
    indent:{left:200},
  });
}
function h(text, lvl=HeadingLevel.HEADING_2) {
  return new Paragraph({text, heading:lvl, spacing:{before:280, after:140}});
}
function bullets(items, tag) {
  return items.map(t => {
    const o = {children:[new TextRun({text:t, size:22, font:'Times New Roman'})],
               bullet:{level:0}, spacing:{after:80, line:300}};
    if (C[tag]) o.shading = {type:ShadingType.CLEAR, fill:C[tag], color:'auto'};
    return new Paragraph(o);
  });
}
function cell(text, {bold=false, w=3000, fill=null}={}) {
  const o = {
    width:{size:w, type:WidthType.DXA},
    children:[new Paragraph({children:[new TextRun({text, bold, size:20, font:'Times New Roman'})],
                             spacing:{after:40}})],
  };
  if (fill) o.shading = {type:ShadingType.CLEAR, fill, color:'auto'};
  return new TableCell(o);
}
function table(rows, widths, tag) {
  const fill = C[tag];
  return new Table({
    columnWidths: widths,
    width:{size: widths.reduce((a,b)=>a+b,0), type:WidthType.DXA},
    rows: rows.map((r,i) => new TableRow({
      children: r.map((t,j) => cell(t, {bold:i===0, w:widths[j], fill: i===0 ? 'EFEFEF' : fill})),
      tableHeader: i===0,
    })),
  });
}

